/// Glifos esenciales de 8x16 para renderizado de texto en modo gráfico
/// Cada fila de 16 píxeles de alto se representa por un byte (8 píxeles de ancho).
pub fn get_glyph(c: char) -> &'static [u8; 16] {
    let ascii = c as usize;
    if ascii >= 32 && ascii < 128 {
        &BASIC_FONT_8X16[ascii - 32]
    } else {
        &GLYPH_UNKNOWN
    }
}

/// Métricas tipográficas proporcionales de alta definición para cada glifo ASCII 32..127
/// Devuelve: (columna_inicial, ancho_glifo, avance_horizontal)
/// Permite tipografía de ancho variable con espaciado natural sin huecos VGA
pub fn get_glyph_metrics(c: char) -> (usize, usize, usize) {
    if c == ' ' {
        return (0, 0, 4); // Espacio proporcional de 4 píxeles
    }
    let ascii = c as usize;
    if ascii < 32 || ascii >= 128 {
        return (0, 8, 8);
    }
    let glyph = &BASIC_FONT_8X16[ascii - 32];
    let mut min_col = 8;
    let mut max_col = 0;
    let mut has_pixel = false;

    for row in 0..16 {
        let byte = glyph[row];
        if byte != 0 {
            for col in 0..8 {
                let bit = (byte >> (7 - col)) & 1;
                if bit == 1 {
                    has_pixel = true;
                    if col < min_col {
                        min_col = col;
                    }
                    if col > max_col {
                        max_col = col;
                    }
                }
            }
        }
    }

    if !has_pixel {
        return (0, 0, 4);
    }

    let glyph_w = (max_col - min_col) + 1;
    // Añadimos 1 píxel de kerning/espaciado entre letras, con un ancho de avance mínimo de 3px
    let advance = (glyph_w + 1).max(3);
    (min_col, glyph_w, advance)
}

